using System.Globalization;
using System.Text;
using Unity.Multiplayer.Hosting.Cli.Packaging;

namespace Unity.Multiplayer.Hosting.Cli.CloudInit;

/// <summary>
/// Renders the "cloud-init/startup script that runs the container + rendezvous" step for any
/// provider that lands on a plain Linux box with SSH (today: <c>GenericVpsProvisioner</c>; the
/// plain-VPS and big-cloud providers in UM-T26/UM-T27 reuse it, wrapping the same bootstrap script
/// into their own cloud-init <c>write_files</c>/<c>runcmd</c> user-data instead of running it over
/// SSH directly).
/// </summary>
public static class CloudInitRenderer
{
    /// <summary>The rendered compose file's name on the host.</summary>
    public const string ComposeFileName = "docker-compose.yml";

    /// <summary>The rendezvous service's published TCP port, in every rendered compose file.</summary>
    public const int RendezvousPort = 8080;

    /// <summary>The GHCR token's path on the host, written once by provisioning and removed by the bootstrap script.</summary>
    public const string GhcrTokenPath = "/tmp/mp-host-ghcr-token";

    /// <summary>
    /// The package's working directory inside the image -- must match
    /// <c>Unity.Multiplayer.Core.ServerPackageDockerfile.WorkDir</c> (Hosting.Cli does not reference
    /// Core, so this is a deliberate, documented second copy: UM-LAW-4). <see cref="RenderCompose"/>'s
    /// pulled image is always built from a package whose own Dockerfile (written by the Unity Editor's
    /// Build Server Package step) sets this as <c>WORKDIR</c>, so <c>manifest.Logs</c>/<c>manifest.Saves</c>
    /// (relative directory names) resolve under it -- mounting a volume anywhere else leaves the game
    /// writing into the container's throwaway layer instead.
    /// </summary>
    private const string ContainerWorkDir = "/srv/game";

    /// <summary>
    /// A <c>docker-compose.yml</c> that runs the pushed image (by reference, never built on the
    /// host) beside the rendezvous service, shaped like
    /// <see cref="Unity.Multiplayer.Core.GenericVpsProfile.ComposeCompose"/> but pulling
    /// <paramref name="imageReference"/> from GHCR instead of building from the package's own
    /// Dockerfile, since mp-host already built and pushed that image in step 2.
    /// </summary>
    public static string RenderCompose(ServerPackageManifest manifest, string imageReference, string rendezvousImage, IReadOnlyDictionary<string, string> environment)
    {
        ArgumentNullException.ThrowIfNull(manifest);
        var text = new StringBuilder();
        text.Append("# Generated by mp-host (UM-T25). Re-running `mp-host deploy`/`mp-host update` rewrites it.\n");
        text.Append("services:\n");
        text.Append("  game:\n");
        text.Append("    image: ").Append(imageReference).Append('\n');
        text.Append("    restart: unless-stopped\n");
        text.Append("    stop_grace_period: ").Append(((int)Math.Ceiling(manifest.StopGraceSeconds) + 5).ToString(CultureInfo.InvariantCulture)).Append("s\n");
        text.Append("    ports:\n");
        foreach (var port in manifest.Ports)
        {
            string binding = port.IsHealthPort ? "127.0.0.1:" : string.Empty;
            text.Append("      - \"").Append(binding).Append(port.Port).Append(':').Append(port.Port).Append('/').Append(port.Protocol).Append("\"\n");
        }

        text.Append("    environment:\n");
        foreach (var (key, value) in environment.OrderBy(kv => kv.Key, StringComparer.Ordinal))
        {
            text.Append("      ").Append(key).Append(": ").Append(YamlQuote(value)).Append('\n');
        }

        text.Append("    volumes:\n");
        text.Append("      - saves:").Append(ContainerPath(manifest.Saves)).Append('\n');
        text.Append("      - logs:").Append(ContainerPath(manifest.Logs)).Append('\n');
        text.Append("    depends_on:\n");
        text.Append("      - rendezvous\n");
        text.Append("  rendezvous:\n");
        text.Append("    image: ").Append(rendezvousImage).Append('\n');
        text.Append("    restart: unless-stopped\n");
        text.Append("    ports:\n");
        text.Append("      - \"").Append(RendezvousPort).Append(':').Append(RendezvousPort).Append("/tcp\"\n");
        text.Append("    environment:\n");
        text.Append("      Rendezvous__RegistrationSecret: ").Append(YamlQuote(environment.GetValueOrDefault("MINDATTIC_RENDEZVOUS_SECRET", ""))).Append('\n');
        text.Append("volumes:\n");
        text.Append("  saves:\n");
        text.Append("  logs:\n");
        return text.ToString();
    }

    /// <summary>
    /// The bootstrap script mp-host uploads and runs over SSH: installs Docker when missing, logs
    /// into GHCR, then pulls and (re)starts the compose stack already uploaded beside it. Exits
    /// non-zero (and therefore fails the SSH command) on any step's failure, so the pipeline sees
    /// a provisioning failure instead of silently leaving a half-started host.
    /// </summary>
    public static string RenderBootstrapScript(string ghcrRegistry, string ghcrUsername)
    {
        var text = new StringBuilder();
        text.Append("#!/bin/sh\n");
        text.Append("set -e\n");
        text.Append("if ! command -v docker >/dev/null 2>&1; then\n");
        text.Append("  curl -fsSL https://get.docker.com | sh\n");
        text.Append("fi\n");
        text.Append("if ! docker compose version >/dev/null 2>&1; then\n");
        text.Append("  echo 'docker compose plugin not found after install' >&2\n");
        text.Append("  exit 1\n");
        text.Append("fi\n");
        text.Append("cat ").Append(GhcrTokenPath).Append(" | docker login ").Append(ghcrRegistry)
            .Append(" --username ").Append(ghcrUsername).Append(" --password-stdin\n");
        text.Append("rm -f ").Append(GhcrTokenPath).Append('\n');
        text.Append("docker compose -f ").Append(ComposeFileName).Append(" pull\n");
        text.Append("docker compose -f ").Append(ComposeFileName).Append(" up -d\n");
        return text.ToString();
    }

    /// <summary>
    /// A <c>#cloud-config</c> user-data document for the plain-VPS cloud providers (UM-T26: Hetzner,
    /// Vultr, DigitalOcean, Linode, OVHcloud): wraps the same <see cref="RenderCompose"/> compose
    /// file and <see cref="RenderBootstrapScript"/> bootstrap script that <c>GenericVpsProvisioner</c>
    /// uploads and runs over SSH, but as cloud-init <c>write_files</c>/<c>runcmd</c> so the provider
    /// runs it automatically on first boot -- no SSH call is needed during provisioning itself (only
    /// for the later status/logs/update calls, once the box has an IP).
    /// </summary>
    public static string RenderUserData(
        ServerPackageManifest manifest, string imageReference, string rendezvousImage,
        IReadOnlyDictionary<string, string> environment,
        string ghcrRegistry, string ghcrUsername, string ghcrToken, string sshPublicKey)
    {
        string compose = RenderCompose(manifest, imageReference, rendezvousImage, environment);
        string bootstrap = RenderBootstrapScript(ghcrRegistry, ghcrUsername);

        var text = new StringBuilder();
        text.Append("#cloud-config\n"); // the only header cloud-init reads as YAML; "#cloud-init" is ignored as unknown user-data
        text.Append("ssh_authorized_keys:\n");
        text.Append("  - ").Append(sshPublicKey.Trim()).Append('\n');
        text.Append("write_files:\n");
        AppendFile(text, "/root/" + ComposeFileName, "'0644'", compose);
        AppendFile(text, GhcrTokenPath, "'0600'", ghcrToken);
        AppendFile(text, "/root/mp-host-bootstrap.sh", "'0755'", bootstrap);
        text.Append("runcmd:\n");
        text.Append("  - [ sh, -c, \"cd /root && sh mp-host-bootstrap.sh\" ]\n");
        return text.ToString();
    }

    private static void AppendFile(StringBuilder text, string path, string permissions, string content)
    {
        text.Append("  - path: ").Append(path).Append('\n');
        text.Append("    permissions: ").Append(permissions).Append('\n');
        text.Append("    content: |\n");
        foreach (string line in content.Replace("\r\n", "\n").Split('\n'))
        {
            text.Append("      ").Append(line).Append('\n');
        }
    }

    /// <summary>
    /// A <c>#cloud-config</c> user-data document for the providers whose VM boot mechanism *is*
    /// cloud-init (AWS EC2, AWS Lightsail, Azure VM via <c>customData</c>): writes
    /// <paramref name="compose"/>, <paramref name="ghcrToken"/> and <paramref name="bootstrapScript"/>
    /// into <paramref name="sshUser"/>'s home directory (the same relative layout
    /// <see cref="RenderCompose"/>'s caller uploads over SSH for GenericVps, so the shared
    /// post-boot SSH operations -- status/logs/update -- run the identical commands against
    /// either kind of host) and runs the bootstrap script once, on first boot only.
    /// </summary>
    public static string RenderCloudConfig(string sshUser, string compose, string bootstrapScript, string ghcrToken)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(sshUser);
        string home = $"/home/{sshUser}";
        var text = new StringBuilder();
        text.Append("#cloud-config\n");
        text.Append("write_files:\n");
        AppendCloudConfigFile(text, $"{home}/{ComposeFileName}", compose, sshUser, "0644");
        AppendCloudConfigFile(text, GhcrTokenPath, ghcrToken, "root", "0600");
        AppendCloudConfigFile(text, $"{home}/mp-host-bootstrap.sh", bootstrapScript, sshUser, "0700");
        text.Append("runcmd:\n");
        text.Append("  - [ sh, -c, \"cd ").Append(home).Append(" && ./mp-host-bootstrap.sh\" ]\n");
        return text.ToString();
    }

    /// <summary>
    /// The plain-shell equivalent of <see cref="RenderCloudConfig"/> for GCE's <c>startup-script</c>
    /// metadata key, which the guest agent runs as a literal script rather than parsing as
    /// cloud-init YAML. Writes the same three files to the same paths and runs the bootstrap script
    /// every boot; the bootstrap script itself is idempotent (re-login, re-pull, re-up), so a reboot
    /// just re-applies the already-running stack instead of double-provisioning it.
    /// </summary>
    public static string RenderStartupScript(string sshUser, string compose, string bootstrapScript, string ghcrToken)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(sshUser);
        string home = $"/home/{sshUser}";
        var text = new StringBuilder();
        text.Append("#!/bin/sh\n");
        text.Append("set -e\n");
        AppendHeredoc(text, $"{home}/{ComposeFileName}", compose);
        AppendHeredoc(text, GhcrTokenPath, ghcrToken);
        AppendHeredoc(text, $"{home}/mp-host-bootstrap.sh", bootstrapScript);
        text.Append("chown ").Append(sshUser).Append(':').Append(sshUser).Append(' ').Append(home).Append('/').Append(ComposeFileName).Append('\n');
        text.Append("chmod 0700 ").Append(home).Append("/mp-host-bootstrap.sh\n");
        text.Append("cd ").Append(home).Append(" && ./mp-host-bootstrap.sh\n");
        return text.ToString();
    }

    private static void AppendCloudConfigFile(StringBuilder text, string path, string content, string owner, string permissions)
    {
        text.Append("  - path: ").Append(path).Append('\n');
        text.Append("    owner: ").Append(owner).Append(':').Append(owner).Append('\n');
        text.Append("    permissions: '").Append(permissions).Append("'\n");
        text.Append("    encoding: b64\n");
        text.Append("    content: ").Append(Convert.ToBase64String(Encoding.UTF8.GetBytes(content))).Append('\n');
    }

    private static void AppendHeredoc(StringBuilder text, string path, string content)
    {
        const string marker = "MPHOST_EOF";
        text.Append("cat > ").Append(path).Append(" <<'").Append(marker).Append("'\n");
        text.Append(content);
        if (!content.EndsWith('\n')) text.Append('\n');
        text.Append(marker).Append('\n');
    }

    /// <summary>
    /// Quotes a scalar for a generated Docker Compose file. Escapes for YAML's own quoting (\ and ")
    /// AND, separately, for Docker Compose's variable interpolation of the parsed file
    /// (<c>$VAR</c> / <c>${VAR}</c>): a literal '$' in a secret or env value (for example a
    /// generated password) would otherwise be read as a variable reference and silently replaced --
    /// usually with an empty string, since there is no such variable -- corrupting the value.
    /// Compose's own escape for a literal '$' is '$$' (UM-T42). The one home for that rule in
    /// Hosting.Cli: both this renderer's compose file and
    /// <see cref="Local.LocalComposeRenderer"/>'s quote through it (UM-T53).
    /// </summary>
    public static string YamlQuote(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("$", "$$") + "\"";

    /// <summary>
    /// A package-relative directory's path inside the container: absolute paths as given, relative
    /// ones under <see cref="ContainerWorkDir"/>. The one home for that rule in Hosting.Cli: both this
    /// renderer's compose file and <see cref="Local.LocalComposeRenderer"/>'s mount their volumes
    /// through it (UM-T38, UM-T51).
    /// </summary>
    public static string ContainerPath(string directory)
    {
        string dir = string.IsNullOrWhiteSpace(directory) ? "." : directory.Trim().Replace('\\', '/').TrimEnd('/');
        return dir.StartsWith("/", StringComparison.Ordinal) ? dir : ContainerWorkDir + "/" + dir;
    }
}
